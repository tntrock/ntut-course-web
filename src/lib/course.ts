/**
 * 課程欄位的顯示規則。
 */

/**
 * 「階段」徽章的文字。沒有東西可顯示時回傳 `null`。
 *
 * **這一欄不是年級。** 站上原本標成「年級」,但學校原始表格的欄位順序是
 * 「課號 | 課程名稱 | **階段** | 學分 | 時數 | 修 | 教師 | …」,年級在「班級」
 * 那一欄(資工四)。
 *
 * 115-1 全學期 2,878 門課實測:
 *
 * - 2,768 門(96%)的值是 `"1"`
 * - 班級是「資工四」的 291 門課,`stage` **全部**是 `"1"` —— 標成「1 年級」
 *   等於對每一門四年級的課說謊
 * - 反過來,班級含「一」的課裡有 6 門 `stage` 是 `"3"`
 *
 * 各系所填法還不一致(體育專項(七)~(十一)全是 `3`;智動的國文在二/三/四年級
 * 分別是 `3`/`5`/`7`)。**所以不猜語意**,學校填什麼就顯示什麼,只是改用它自己
 * 的欄位名。
 *
 * `"1"` 不顯示:96% 的課都是這個值,擺在每一頁只是雜訊而沒有任何資訊。
 * 需要對照的話,課程頁本來就有「學校原始頁面」的連結。
 */
export function stageBadge(stage: string | null): string | null {
  const value = stage?.trim()
  if (!value || value === '1') return null
  return `階段 ${value}`
}
